/*
    This class represents a stakeholder in the store. A stakeholder is an individual or entity that has an interest in the store, typically through ownership or investment. The class contains attributes to represent the percentage of the store owned (stake) and the amount of capital invested in the store (investment).
*/

package model;

public interface Stakeholder {
    public static float stake = 0.0f; // percentage of the store owned
    public static double investment = 0.0; // amount of capital invested in the store
}
